/**
 * 매장의 기존 카테고리를 넘겨 분류명을 맞춰 쓰게 한다.
 * 이름이 그대로 일치해야 매핑 단계에서 기존 카테고리로 붙는다 —
 * 어긋나면 "찌개"와 "찌개류"가 각각 만들어져 사장님이 손으로 합쳐야 한다.
 */
export function buildMenuVisionPrompt(existingCategoryNames: string[]): string {
  const lines = ["이 사진들에서 메뉴를 추출해줘."];

  if (existingCategoryNames.length > 0) {
    lines.push(
      "",
      "이 매장에는 아래 카테고리가 이미 있다. 사진의 분류가 이 중 하나에 해당하면",
      "표기를 바꾸지 말고 아래 이름 그대로 categoryName에 넣어라.",
      ...existingCategoryNames.map((name) => `- ${name}`),
      "",
      "해당하는 게 없으면 사진에 적힌 분류 제목을 그대로 쓰고, 분류 제목 자체가 없으면 null."
    );
  }

  return lines.join("\n");
}
